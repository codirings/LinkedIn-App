#!/usr/bin/env node
/**
 * Cross-platform (Windows / macOS / Linux) env loader. No dependencies.
 *
 *   .env  ->  src/config/env.generated.js
 *
 * If `.env` does not exist it is created from `.env.example`.
 * Runs automatically on `npm install`, `npm start`, `npm run android|ios`, `npm test`.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const examplePath = path.join(root, '.env.example');
const outPath = path.join(root, 'src', 'config', 'env.generated.js');
const REQUIRED = ['GOOGLE_WEB_CLIENT_ID'];

if (!fs.existsSync(envPath)) {
  if (!fs.existsSync(examplePath)) {
    console.error('[env] Missing both .env and .env.example');
    process.exit(1);
  }
  fs.copyFileSync(examplePath, envPath);
  console.log('[env] Created .env from .env.example - edit it if you use your own Firebase project.');
}

const vars = {};
fs.readFileSync(envPath, 'utf8')
  .split(/\r?\n/) // handles CRLF files edited on Windows
  .forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      return;
    }
    const eq = trimmed.indexOf('=');
    if (eq === -1) {
      return;
    }
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  });

const missing = REQUIRED.filter((k) => !vars[k]);
if (missing.length) {
  console.error(`[env] Missing required variable(s) in .env: ${missing.join(', ')}`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(outPath), {recursive: true});
fs.writeFileSync(
  outPath,
  '// AUTO-GENERATED by scripts/generate-env.js from .env - do not edit or commit.\n' +
    `module.exports = ${JSON.stringify(vars, null, 2)};\n`,
);
console.log('[env] Wrote src/config/env.generated.js');
